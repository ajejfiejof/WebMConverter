using System;
using WebMConverter.Core.Filters;
using WebMConverter.Core.VapourSynth;
using Xunit;

namespace WebMConverter.Core.Tests;

public sealed class VapourSynthTests
{
    [Fact]
    public void GoldenScript()
    {
        var options = new VapourSynthOptions
        {
            SourceFile = "/tmp/in.mp4",
            CacheFile = "/tmp/in.ffindex",
            AssumeFps = 30,
            Crop = (10, 20, 30, 40),
            Resize = (1280, 720),
            FlipHorizontal = true,
        };
        options.Trims.Add((90, 270));

        string script = VapourSynthScript.Generate(options);
        string expected =
            "# Generated by WebMConverter. Requires VapourSynth with the ffms2 plugin.\n" +
            "# Feed it to ffmpeg on Linux via: vspipe --y4m script.vpy - | ffmpeg -f yuv4mpegpipe -i pipe:0 ...\n" +
            "import vapoursynth as vs\n" +
            "core = vs.core\n" +
            "clip = core.ffms2.Source(source=r'/tmp/in.mp4', cachefile=r'/tmp/in.ffindex')\n" +
            "clip = core.std.Trim(clip, 90, 270)\n" +
            "clip = core.std.AssumeFPS(clip, fpsnum=30, fpsden=1)\n" +
            "clip = core.std.Crop(clip, left=10, right=20, top=30, bottom=40)\n" +
            "clip = core.resize.Bicubic(clip, 1280, 720)\n" +
            "clip = core.std.FlipHorizontal(clip)\n" +
            "clip.set_output()\n";
        Assert.Equal(expected.Replace("\n", Environment.NewLine), script);
    }

    [Fact]
    public void MultiTrimSplices()
    {
        var options = new VapourSynthOptions { SourceFile = "a.mkv", CacheFile = "a.ffindex" };
        options.Trims.Add((0, 100));
        options.Trims.Add((200, 300));
        string script = VapourSynthScript.Generate(options);
        Assert.Contains("clip = core.std.Splice([core.std.Trim(clip, 0, 100), core.std.Trim(clip, 200, 300)])", script);
    }

    [Fact]
    public void FromFiltersMapsFramesAndReportsGaps()
    {
        var filters = new FilterSet
        {
            Trim = new TrimFilter(30, 90),
            Resize = new ResizeFilter(640, 480),
            Dub = new DubFilter("a.wav", "a.ffindex", DubMode.JustDub),
            Rotate = new RotateFilter(RotateMode.Right, flipHorizontal: false, flipVertical: true),
        };
        var options = VapourSynthScript.FromFilters("in.mp4", "in.ffindex", filters, _ => TimeSpan.Zero, fps: 30);

        Assert.Single(options.Trims);
        Assert.Equal((30, 90), options.Trims[0]);
        Assert.Equal((640, 480), options.Resize);
        Assert.True(options.FlipVertical);

        var notes = VapourSynthScript.UnsupportedNotes(filters);
        Assert.Contains(notes, n => n.StartsWith("Dub"));
        Assert.Contains(notes, n => n.StartsWith("Rotate mode"));
    }

    [Fact]
    public void PythonQuoteEscapes()
    {
        Assert.Equal("/tmp/in.mp4", VapourSynthScript.PythonQuote("/tmp/in.mp4"));
        Assert.Equal("C:\\\\vid\\\\a\\'b", VapourSynthScript.PythonQuote("C:\\vid\\a'b"));
    }
}
