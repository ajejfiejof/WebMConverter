using System;
using System.Collections.Generic;
using System.Text;
using WebMConverter.Core.Filters;

namespace WebMConverter.Core.VapourSynth;

/// <summary>
/// Options for generating a VapourSynth (.vpy) script. Only filters with a
/// certain core-plugin mapping are emitted; everything else is reported via
/// <see cref="VapourSynthScript.UnsupportedNotes"/> so the UI can warn.
/// </summary>
public sealed class VapourSynthOptions
{
    public string SourceFile { get; set; } = string.Empty;
    public string CacheFile { get; set; } = string.Empty;
    public List<(int First, int Last)> Trims { get; } = new();
    public double? AssumeFps { get; set; }
    public (int Left, int Right, int Top, int Bottom)? Crop { get; set; }
    public (int Width, int Height)? Resize { get; set; }
    public bool FlipHorizontal { get; set; }
    public bool FlipVertical { get; set; }
}

public static class VapourSynthScript
{
    /// <summary>
    /// Builds script options from the active filter set. Frame numbers come
    /// from the caller (fps clock); unmapped filters are skipped here and
    /// listed by <see cref="UnsupportedNotes"/>.
    /// </summary>
    public static VapourSynthOptions FromFilters(
        string sourceFile,
        string cacheFile,
        FilterSet filters,
        Func<int, TimeSpan> frameToTime,
        double fps)
    {
        var options = new VapourSynthOptions
        {
            SourceFile = sourceFile,
            CacheFile = cacheFile,
        };

        int ToFrames(double seconds) => Math.Max(0, (int)Math.Round(seconds * fps));

        if (filters.Trim is not null)
            options.Trims.Add((filters.Trim.TrimStart, filters.Trim.TrimEnd));
        if (filters.MultipleTrim is not null)
        {
            foreach (var trim in filters.MultipleTrim.Trims)
                options.Trims.Add((trim.TrimStart, trim.TrimEnd));
        }

        if (filters.Rate is not null && filters.Rate.Multiplier > 0)
            options.AssumeFps = fps * filters.Rate.Multiplier / 100;

        if (filters.Crop is not null)
        {
            // std.Crop takes positive per-side pixel counts; our model stores
            // right/bottom as negative-for-shrink (legacy convention).
            options.Crop = (
                Math.Max(0, filters.Crop.Left),
                Math.Max(0, -filters.Crop.Right),
                Math.Max(0, filters.Crop.Top),
                Math.Max(0, -filters.Crop.Bottom));
        }

        if (filters.Resize is not null)
            options.Resize = (filters.Resize.TargetWidth, filters.Resize.TargetHeight);

        if (filters.Rotate is not null)
        {
            options.FlipHorizontal = filters.Rotate.FlipHorizontal;
            options.FlipVertical = filters.Rotate.FlipVertical;
        }

        return options;
    }

    /// <summary>Names of active filters with no .vpy mapping.</summary>
    public static List<string> UnsupportedNotes(FilterSet filters)
    {
        var notes = new List<string>();
        if (filters.Caption is not null)
            notes.Add("Caption (no VapourSynth text renderer mapped)");
        if (filters.Dub is not null)
            notes.Add("Dub (audio dubbing needs plugins)");
        if (filters.Deinterlace is not null)
            notes.Add("Deinterlace (needs an external plugin)");
        if (filters.Denoise is not null)
            notes.Add("Denoise (needs an external plugin)");
        if (filters.Levels is not null)
            notes.Add("Levels (no mapping)");
        if (filters.Overlay is not null)
            notes.Add("Overlay (no mapping)");
        if (filters.Fade is not null)
            notes.Add("Fade (no mapping)");
        if (filters.Reverse is not null)
            notes.Add("Reverse (no mapping)");
        if (filters.Rotate is not null && filters.Rotate.Mode != RotateMode.None)
            notes.Add("Rotate mode (only flips map to std)");
        if (filters.Subtitle is not null)
            notes.Add("Subtitle (needs a subtext plugin for TextFile)");
        return notes;
    }

    public static string Generate(VapourSynthOptions options)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by WebMConverter. Requires VapourSynth with the ffms2 plugin.");
        sb.AppendLine("# Feed it to ffmpeg on Linux via: vspipe --y4m script.vpy - | ffmpeg -f yuv4mpegpipe -i pipe:0 ...");
        sb.AppendLine("import vapoursynth as vs");
        sb.AppendLine("core = vs.core");
        sb.AppendLine($"clip = core.ffms2.Source(source=r'{PythonQuote(options.SourceFile)}', cachefile=r'{PythonQuote(options.CacheFile)}')");

        if (options.Trims.Count == 1)
            sb.AppendLine($"clip = core.std.Trim(clip, {options.Trims[0].First}, {options.Trims[0].Last})");
        else if (options.Trims.Count > 1)
        {
            var parts = new List<string>();
            foreach (var (first, last) in options.Trims)
                parts.Add($"core.std.Trim(clip, {first}, {last})");
            sb.AppendLine($"clip = core.std.Splice([{string.Join(", ", parts)}])");
        }

        if (options.AssumeFps is double fps && fps > 0)
            sb.AppendLine($"clip = core.std.AssumeFPS(clip, fpsnum={fps:G17}, fpsden=1)");

        if (options.Crop is var (left, right, top, bottom))
            sb.AppendLine($"clip = core.std.Crop(clip, left={left}, right={right}, top={top}, bottom={bottom})");

        if (options.Resize is var (w, h))
            sb.AppendLine($"clip = core.resize.Bicubic(clip, {w}, {h})");

        if (options.FlipHorizontal)
            sb.AppendLine("clip = core.std.FlipHorizontal(clip)");
        if (options.FlipVertical)
            sb.AppendLine("clip = core.std.FlipVertical(clip)");

        sb.AppendLine("clip.set_output()");
        return sb.ToString();
    }

    internal static string PythonQuote(string value) =>
        value.Replace("\\", "\\\\").Replace("'", "\\'");
}
